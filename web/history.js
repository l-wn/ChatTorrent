// Saved chats: stored in this browser, scoped by mesh, synced across its tabs.
//
// A record, `v: 1`:
//
//   { v, id, mesh, model, weights, title, created, updated, rev,
//     messages: [{ role: 'user'|'assistant', text, reasoning, meta, opts }],
//     ids: Uint32Array }
//
// `ids` are the token ids the peers were fed, which a rebuild re-feeds
// (route.js's rebuild()). `mesh` is the room's historyTag: a store opened for
// one mesh cannot read or change another's chats. `model` and `weights` name
// the checkpoint the ids belong to. `opts` is { chat, thinking }, how the turn
// was wrapped. `rev` increases on every save.

// The database and export names keep the project's old name, so saved chats
// and earlier exports still open.
const DB = 'chattorrent';
const STORE = 'chats';
export const VERSION = 1;
export const FORMAT = 'chattorrent-chats';
export const TITLE_MAX = 60;

// --- Records ---

// A chat's title in the list: its first user message on one line, truncated.
// Not generated by the model, which would cost an extra turn on the mesh.
export function titleFrom(text) {
    const line = String(text ?? '').replace(/\s+/g, ' ').trim();
    if (line.length <= TITLE_MAX) return line || 'New chat';
    return `${line.slice(0, TITLE_MAX - 1).trimEnd()}…`;
}

export function newRecord({ mesh, model = null, weights = null, now = Date.now() }) {
    return {
        v: VERSION, id: crypto.randomUUID(), mesh, model, weights,
        title: '', created: now, updated: now, rev: 0,
        messages: [], ids: new Uint32Array(0),
    };
}

// Group into Today / Yesterday / Earlier by local midnight, newest first.
// Empty groups are omitted.
export function groupByDay(recs, now = Date.now()) {
    const midnight = new Date(now);
    midnight.setHours(0, 0, 0, 0);
    const today = midnight.getTime();
    const yesterday = new Date(midnight).setDate(midnight.getDate() - 1);
    const groups = [['Today', []], ['Yesterday', []], ['Earlier', []]];
    for (const r of [...recs].sort((a, b) => b.updated - a.updated)) {
        groups[r.updated >= today ? 0 : r.updated >= yesterday ? 1 : 2][1].push(r);
    }
    return groups.filter(([, chats]) => chats.length).map(([label, chats]) => ({ label, chats }));
}

// --- Backends ---
//
// Storage by id, with no scoping. openHistory() adds the mesh scope.
//
//   list(mesh)      every record of that mesh
//   get(id)         one record, or null
//   put(rec)        insert or replace
//   delete(id)
//   countNot(mesh)  how many records belong to other meshes

// For tests, and for a browser that denies IndexedDB (chats then last only as
// long as the tab). Stores clones, as IndexedDB does, so callers never share a
// stored record.
export function memoryBackend() {
    const recs = new Map();
    return {
        async list(mesh) { return [...recs.values()].filter((r) => r.mesh === mesh).map((r) => structuredClone(r)); },
        async get(id) { return recs.has(id) ? structuredClone(recs.get(id)) : null; },
        async put(rec) { recs.set(rec.id, structuredClone(rec)); },
        async delete(id) { recs.delete(id); },
        async countNot(mesh) { return [...recs.values()].filter((r) => r.mesh !== mesh).length; },
    };
}

const done = (req) => new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
});

export function idbBackend(name = DB) {
    const db = new Promise((resolve, reject) => {
        const req = indexedDB.open(name, 1);
        req.onupgradeneeded = () => {
            const store = req.result.createObjectStore(STORE, { keyPath: 'id' });
            store.createIndex('mesh', 'mesh');
        };
        req.onsuccess = () => resolve(req.result);
        req.onerror = () => reject(req.error);
        req.onblocked = () => reject(new Error('chat storage is blocked by another tab'));
    });
    const store = async (mode) => (await db).transaction(STORE, mode).objectStore(STORE);
    return {
        async list(mesh) { return done((await store('readonly')).index('mesh').getAll(mesh)); },
        async get(id) { return (await done((await store('readonly')).get(id))) ?? null; },
        async put(rec) { await done((await store('readwrite')).put(rec)); },
        async delete(id) { await done((await store('readwrite')).delete(id)); },
        async countNot(mesh) {
            const s = await store('readonly');
            const [all, mine] = await Promise.all([done(s.count()), done(s.index('mesh').count(mesh))]);
            return all - mine;
        },
    };
}

// --- The store ---

// This tab's chats in `mesh`. `channel` is a BroadcastChannel (or an object
// with the same interface) shared by the site's tabs. Every change is posted
// as { mesh, id, rev, op }, and onChange() listeners receive the changes other
// tabs make to this mesh.
export function openHistory({ mesh, backend = idbBackend(), channel = null,
                              now = () => Date.now(), persist = requestPersist } = {}) {
    if (!mesh) throw new Error('a chat store needs a mesh to be scoped to');
    const listeners = new Set();
    let persisted = false;

    const mine = (rec) => rec?.mesh === mesh;
    const announce = (id, rev, op) => channel?.postMessage({ mesh, id, rev, op });
    const hear = (e) => {
        const m = e?.data;
        if (m?.mesh !== mesh) return;
        for (const fn of listeners) fn(m);
    };
    channel?.addEventListener('message', hear);

    return {
        mesh,

        // Newest first.
        async list() {
            return (await backend.list(mesh)).filter(mine).sort((a, b) => b.updated - a.updated);
        },

        // Null for a chat that does not exist or belongs to another mesh. A
        // caller cannot tell the two apart.
        async get(id) {
            const rec = await backend.get(id);
            return mine(rec) ? rec : null;
        },

        // Sets `updated` and `rev` on `rec` itself, so the caller's copy
        // matches what was stored.
        async save(rec) {
            if (!mine(rec)) throw new Error(`that chat belongs to another cluster (${rec?.mesh})`);
            if (rec.title === '') {
                rec.title = titleFrom(rec.messages.find((m) => m.role === 'user')?.text);
            }
            rec.updated = now();
            rec.rev = (rec.rev ?? 0) + 1;
            await backend.put(rec);
            announce(rec.id, rec.rev, 'put');
            // Requested once, on the first save. If refused, the browser may
            // evict the chats under storage pressure.
            if (!persisted) { persisted = true; persist(); }
            return rec;
        },

        async rename(id, title) {
            const rec = await this.get(id);
            if (!rec) return null;
            rec.title = titleFrom(title);
            return this.save(rec);
        },

        async remove(id) {
            if (!(await this.get(id))) return false;
            await backend.delete(id);
            announce(id, null, 'delete');
            return true;
        },

        // Delete this mesh's chats. Returns how many were deleted.
        async forgetAll() {
            const recs = await this.list();
            for (const r of recs) await backend.delete(r.id);
            if (recs.length) announce(null, null, 'clear');
            return recs.length;
        },

        // How many chats are saved for other meshes. Only a count; their
        // titles are not read.
        countElsewhere() { return backend.countNot(mesh); },

        onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); },
        close() { listeners.clear(); channel?.removeEventListener('message', hear); },
    };
}

// Ask for durable storage, so the browser does not clear chats to free space.
// Best effort: unsupported or refused is not an error.
export async function requestPersist() {
    try { return await navigator.storage?.persist?.() ?? false; } catch { return false; }
}

// --- Export and import ---
//
//   { format: 'chattorrent-chats', v: 1, exported, chats: [record, ids as base64] }
//
// The ids are little-endian u32s in base64: a 4096-token chat is 22 KB of
// text, several times smaller than a JSON array.

const b64 = (bytes) => {
    let s = '';
    for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
    return btoa(s);
};

export function idsToBase64(ids) {
    const view = new DataView(new ArrayBuffer(ids.length * 4));
    ids.forEach((id, i) => view.setUint32(i * 4, id, true));
    return b64(new Uint8Array(view.buffer));
}

export function idsFromBase64(str) {
    const bytes = Uint8Array.from(atob(str), (c) => c.charCodeAt(0));
    if (bytes.length % 4) throw new Error('token ids are not a whole number of u32s');
    const view = new DataView(bytes.buffer);
    return Uint32Array.from({ length: bytes.length / 4 }, (_, i) => view.getUint32(i * 4, true));
}

export function exportChats(recs, now = Date.now()) {
    return {
        format: FORMAT, v: VERSION, exported: new Date(now).toISOString(),
        chats: recs.map((r) => ({ ...r, ids: idsToBase64(r.ids) })),
    };
}

// Convert an export to records ready to save into `mesh`. The file's own mesh
// is ignored, since importing moves chats into this mesh. Each record gets a
// new id, so importing twice makes duplicates.
export function importChats(json, mesh, now = Date.now()) {
    if (json?.format !== FORMAT) throw new Error('not a ClusterChat chat export');
    if (json.v !== VERSION) throw new Error(`chat export version ${json.v} is not supported`);
    if (!Array.isArray(json.chats)) throw new Error('the export has no chats');
    return json.chats.map((c) => {
        if (!Array.isArray(c.messages)) throw new Error('a chat in the export has no messages');
        return {
            ...newRecord({ mesh, model: c.model ?? null, weights: c.weights ?? null, now }),
            title: typeof c.title === 'string' ? c.title : '',
            created: Number(c.created) || now,
            messages: c.messages.map(({ role, text, reasoning = null, meta = '', opts = {} }) =>
                ({ role, text: String(text ?? ''), reasoning, meta, opts })),
            ids: idsFromBase64(c.ids ?? ''),
        };
    });
}
